"""Each actual stage: five isolated updates, direct objective and state replay.

No scientific outcome is generated by this admission. All model, optimizer,
scheduler, gradients, modes and RNG are restored before production starts.
"""
import io
from case_runtime import *
from updates import update


def direct_reference(a, batch, info, stage):
    """Independent explicit composition of the surviving S objective terms."""
    x = a.map_tensor_to_device(batch[0])
    task = torch.tensor([int(v) for v in batch[1]], device='cuda')
    a.optimizer.zero_grad()
    feature = x['feature']
    if feature.ndim == 5:
        feature = feature.squeeze(1)
    assert feature.shape[1:] == (8, 4, 512)
    h = a.policy.module.temporal_encode(feature)[:, -1]
    distribution = a.policy.module.policy_head(h)
    aligned = INPUT['variant'] == 'ALIGN'
    valid = x['causal_bc_valid'].bool() if aligned else torch.ones(len(h), device=h.device, dtype=torch.bool)
    target = x['next_action'] if aligned else x['actions'].squeeze(1)[:, -1]
    nll = -distribution.log_prob(target) * a.policy.module.policy_head.loss_coef
    bc = nll[valid].mean() if valid.any() else nll.sum() * 0
    mask = task == stage
    previous = [a.refs[j if k == stage else k] for j, k in info['selected_pairs']]
    ifa = angular_mean(h[mask], a.refs[stage], previous, a.cfg.gamma) if mask.any() else h.sum() * 0
    loss = bc + .1 * ifa
    (a.loss_scale * loss).backward()
    assert torch.isfinite(loss)
    assert all(p.grad is None or torch.isfinite(p.grad).all() for p in a.policy.parameters())
    torch.nn.utils.clip_grad_norm_(a.policy.parameters(), a.cfg.train.grad_clip)
    a.optimizer.step()
    a.scheduler.step()
    a.step += 1
    return dict(loss=float(loss.detach()), bc=float(bc.detach()), ifa=float(ifa.detach()),
                valid=int(valid.sum()), invalid=int((~valid).sum()))


def admit(a, ds, info, stage, arm):
    variant = INPUT['variant']
    assert variant in ('ALIGN', 'MLR')
    start = capture(a)
    before = CALLS['admission']
    # Deterministic index selection; cover old/current and valid/invalid windows
    # when available without advancing the production sampler or its RNG.
    pools = [[i for i, r in enumerate(ds.rows) if r['task'] < stage and r['bc_valid']],
             [i for i, r in enumerate(ds.rows) if r['task'] == stage and r['bc_valid']],
             [i for i, r in enumerate(ds.rows) if not r['bc_valid']],
             list(range(len(ds)))]
    ids = []
    for pool, limit in zip(pools, [3, 4, 2, 10]):
        for i in pool[:limit]:
            if i not in ids:
                ids.append(i)
            if len(ids) == 10:
                break
        if len(ids) == 10:
            break
    assert len(ids) == 10
    batch = torch.utils.data.default_collate([ds[i] for i in ids])

    first = update(a, batch, info, stage)
    one = capture(a)
    restore(a, start)
    first_reference = direct_reference(a, batch, info, stage)
    assert first == first_reference and equal(one, capture(a))

    restore(a, one)
    second = update(a, batch, info, stage)
    two = capture(a)
    stream = io.BytesIO()
    torch.save(dict(state=one,step=one['step']), stream)
    serialized_bytes = stream.tell()
    assert serialized_bytes < 350000000
    stream.seek(0)
    restored = torch.load(stream, map_location='cpu')
    assert equal(one, restored['state']) and restored['step'] == start['step'] + 1
    restore(a, restored['state'])
    replay = update(a, batch, info, stage)
    assert replay == second and equal(two, capture(a))
    restore(a, restored['state'])
    second_reference = direct_reference(a, batch, info, stage)
    assert second == second_reference and equal(two, capture(a))
    assert CALLS['admission'] - before == 5

    restore(a, start)
    x = a.map_tensor_to_device(batch[0])
    h = hidden(a.policy.module, x['feature'])
    empty = dict(x, causal_bc_valid=torch.zeros_like(x['causal_bc_valid'], dtype=torch.bool))
    masked_value, validity = masked_bc(a.policy.module, h, empty, variant == 'ALIGN')
    if variant == 'ALIGN':
        assert not validity.any() and float(masked_value.detach()) == 0 and masked_value.requires_grad
    else:
        assert validity.all() and torch.isfinite(masked_value) and masked_value.requires_grad
    restore(a, start)
    assert equal(start, capture(a))
    result = dict(status='PASS_OWN_GPU_STRIPPED_S_ADMISSION', stage=stage, arm=arm, variant=variant,
        optimizer_calls=5, extra_autograd_calls=0, production_calls_added=0, environments=0,
        direct_bc_ifa_first_update_full_state_exact=True,
        direct_bc_ifa_second_update_full_state_exact=True,
        roundtrip_exact=True, next_step_exact=True, restore_initial_exact=True,
        empty_mask_differentiable_zero=True if variant == 'ALIGN' else None,
        mlr_ignores_alignment_validity=True if variant == 'MLR' else None, admission_indices=ids,
        valid_samples=first['valid'], invalid_samples=first['invalid'],
        serialized_bytes=serialized_bytes, strict_keys=len(a.policy.state_dict()),
        objective=('ALIGN_BC' if variant == 'ALIGN' else 'ORIGINAL_BC')+' + 0.1*IFA', execution_expert=False, retention=False,
        support_weights=False, candidate_gating=False, contract=verify())
    write(R / ('ADMISSION_%s_%d.json' % (arm, stage)), result)
    return result
